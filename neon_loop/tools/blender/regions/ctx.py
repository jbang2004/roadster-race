"""
Region interface: the `ctx` object and the module loader.  COORDINATOR-OWNED (region agents do not edit this file; see REGIONS.md).

A region module (regions/front.py, side.py, rear.py) has NAME = 'front' | 'side' | 'rear' and any of these hooks (all take ctx first):

    shell_post(ctx)                  cut / colour the HI body shell.  Order in the build:  REAR  ->  [wheel-arch cut]  ->  FRONT, SIDE  ->  [floor]
    build(ctx, level) -> [Object]    static parts, joined into the 'Body' node.  level 0 = hi, 1 = lod1, 2 = lod2.  Objects must be fresh (not shared).
    nodes(ctx, level) -> {name: Obj} separately exported nodes, parented to the car root in dict order (rear: Thrusters, Wing)
    decals(ctx, level) -> [Object]   patches joined into the 'Decals' node (rear: Decal_plate)
    lod_post(ctx, level, body)       touch the decimated LOD body (rear: re-colour the tail)
    meta(ctx) -> dict                merged into car_meta.json ('decals' is merged key by key; rear: wing, decals.plate)

Everything a region may use comes through `ctx` (below) or `import common` (pure helpers, HUBS, ...); region code must not read build_game_car.py globals.

ctx attributes (set by build_game_car.py)
  level            current level (0 hi, 1 lod1, 2 lod2) while a hook runs;  region = name of the region whose hook is running
  body             the HI body object during shell_post; the current level's body object afterwards
  surf_hi          Surf of the HI body (always available after the shell is finished);   surf = Surf of this level's body (= surf_hi at level 0,
                   the decimated body at levels 1 and 2; set by the coordinator around the REAR hooks).  Surf.cast(origin, dir, off=0, maxd=6) -> (point, normal) | (None, None)
                   P0 note: FRONT and SIDE always cast on surf_hi (as before the split, also at the LODs); REAR casts on surf.
  mk(bm, name, mat, smooth) -> Object    object from a bmesh (frees it);   mat(name) -> material;   mat_of(level, name) -> material name for this level or None (dropped)
  patch(name, mat_name, ranges, origin_fn, direction, off, nu, nv, ...)   grid projected onto ctx.surf (see build_game_car.patch)
  CB, Builder, W_DARK, smooth, mark_sharp(me, deg), cb_obj(cb, name, mat_name, keep_color=False, sharp=40), link(ob), join(objs, name)
  A                shell interface: A.D (design2 module: curves, anchors), A.S2 (shell2 module), A.glass_half_width(x)
  HUBS ((x, side), ...), HUB_Z, R_ARCH: the wheel ARCHES (centres x -1.487 / 1.61, z 0.39; the old hubs)
  R_TYRE, WHEEL_Z (front, rear);  WHEEL_Y: the wheels themselves (hub |y|, z and tyre radius per axle; build_game_car.py, CALIB.md)
  oldbody / front_r2   the --oldbody / --front flags;   argv, flag(name), arg(name, default)
  cache            dict a region may use to memoise constants for one build (rear: FAS_LEAN, the stowed wing pose)
  report(key, value)   adds a note to this region's entry in the build REPORT
"""
import importlib.util
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REGIONS = ('front', 'side', 'rear')
HOOKS = ('shell_post', 'build', 'nodes', 'decals', 'lod_post', 'meta')


class Ctx:
    def __init__(self, **kw):
        self.level = 0
        self.region = None
        self.cache = {}
        self.notes = {}                 # region -> {key: value}
        self.surf = None
        self.surf_hi = None
        self.body = None
        self.__dict__.update(kw)

    def flag(self, name):
        return ('--' + name) in self.argv

    def arg(self, name, default=None):
        k = '--' + name
        return self.argv[self.argv.index(k) + 1] if k in self.argv else default

    def report(self, key, value):
        self.notes.setdefault(self.region or '?', {})[key] = value


def parse_live(spec):
    """'all' | 'none' | 'front' | 'front,rear' -> set of live region names ('none' = every region from regions/_base: the reference build of the last integration)"""
    live = set(REGIONS) if spec in ('all', '') else set() if spec == 'none' else set(s for s in spec.split(',') if s)
    bad = live - set(REGIONS)
    if bad:
        raise SystemExit('--live: unknown region(s) %s (use front|side|rear|all|none)' % sorted(bad))
    return live


def load_regions(live):
    """-> {name: module}.  Live regions come from regions/<r>.py, the others from regions/_base/<r>.py (the snapshot at the last integration)."""
    mods = {}
    for r in REGIONS:
        base = r not in live
        path = os.path.join(HERE, '_base', r + '.py') if base else os.path.join(HERE, r + '.py')
        spec = importlib.util.spec_from_file_location('region_%s%s' % (r, '_base' if base else ''), path)
        m = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(m)
        if getattr(m, 'NAME', None) != r:
            raise SystemExit('%s: NAME must be %r' % (path, r))
        m.SOURCE = 'base' if base else 'live'
        mods[r] = m
    return mods


def call(mods, ctx, region, hook, *args, default=None):
    """run a hook of a region if it has it (ctx.region is set while it runs)"""
    fn = getattr(mods[region], hook, None)
    if fn is None:
        return default
    ctx.region = region
    try:
        return fn(ctx, *args)
    finally:
        ctx.region = None
